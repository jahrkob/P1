#!/usr/bin/env python3
import numpy as np
import matplotlib.pyplot as plt

# ================================
# CONFIG
# ================================
TRACES_PATH  = "data/premade/traces.npy"
TEXTINS_PATH = "data/premade/textins.npy"

BYTE_IDX = 1          # hvilken AES byte (0..15) du vil angribe
